/**
 * Resolves CDN video (GIF) and thumbnail URLs for any exercise in the catalog.
 */
export function resolveCatalogMedia(exerciseNameOrId: string): { videoUrl: string; imageUrl: string; thumbnailUrl: string } | null {
  if (!exerciseNameOrId) return null;
  const clean = exerciseNameOrId.toLowerCase().trim();

  // 1. Direct name match
  let match = EXERCISE_MEDIA_CATALOG[clean];

  // 2. ID match or partial name match
  if (!match) {
    for (const [name, tuple] of Object.entries(EXERCISE_MEDIA_CATALOG)) {
      if (tuple[0] === clean || name.includes(clean) || clean.includes(name)) {
        match = tuple;
        break;
      }
    }
  }

  if (!match) return null;

  const [_, gifFilename, imgFilename] = match;
  return {
    videoUrl: `${CDN_BASE}videos/${gifFilename}`,
    imageUrl: `${CDN_BASE}images/${imgFilename}`,
    thumbnailUrl: `${CDN_BASE}images/${imgFilename}`,
  };
}
